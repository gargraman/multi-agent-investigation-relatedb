"""Service configuration (spec §13.3). Every service validates its config at startup.

Each service subclasses :class:`ServiceSettings` and adds its own fields. Values come from
environment variables (Compose ``env_file: .env``); an invalid or missing required value raises at
import/startup, so a misconfigured container fails its healthcheck instead of running half-set.
"""

from enum import StrEnum

from pydantic import Field, SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict


class NexusEnv(StrEnum):
    LOCAL = "local"
    TEST = "test"
    CI = "ci"


class ServiceSettings(BaseSettings):
    """Settings every Nexus service shares."""

    model_config = SettingsConfigDict(env_file=None, extra="ignore", frozen=True)

    service_name: str = Field(description="Stable service id, e.g. 'orchestrator'.")
    service_version: str = "0.1.0"
    nexus_env: NexusEnv = NexusEnv.LOCAL
    nexus_log_level: str = Field(default="INFO", pattern="^(DEBUG|INFO|WARNING|ERROR)$")

    # Unset in the `lite` profile: tracing still runs (context propagation, log correlation)
    # but nothing is exported.
    otel_exporter_otlp_endpoint: str | None = None

    # This service's own bearer token (generated by `make secrets`).
    service_token: SecretStr = Field(min_length=32)
