"""Service-to-service bearer tokens and the operator actor header (spec §14.1, ADR-005 D4).

Pure functions with no web framework, so services wrap them in their own dependencies.

- Each service has its own token, generated by ``make secrets`` into ``.env`` as
  ``NEXUS_TOKEN_<SERVICE>`` (e.g. ``NEXUS_TOKEN_ORCHESTRATOR``).
- A receiver builds a :class:`TokenRegistry` of the callers it accepts and resolves the
  ``Authorization`` header to a caller id. Comparison is constant-time.
- ``X-Nexus-Actor`` is trusted **only** when the caller is the orchestrator.
"""

import hmac
import os
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass

ORCHESTRATOR = "orchestrator"
ACTOR_HEADER = "X-Nexus-Actor"
_ACTOR_RE = re.compile(r"^operator:[a-z0-9][a-z0-9._-]{0,63}$")


def token_env_var(caller_id: str) -> str:
    return "NEXUS_TOKEN_" + caller_id.upper().replace("-", "_")


@dataclass(frozen=True)
class TokenRegistry:
    tokens: Mapping[str, str]  # caller_id -> token

    @classmethod
    def from_env(
        cls, callers: Iterable[str], env: Mapping[str, str] | None = None
    ) -> "TokenRegistry":
        """Load tokens for ``callers``. A missing or short token is a startup error."""
        env = os.environ if env is None else env
        tokens: dict[str, str] = {}
        for caller in callers:
            value = env.get(token_env_var(caller), "")
            if len(value) < 32:
                raise ValueError(f"{token_env_var(caller)} is missing or shorter than 32 chars")
            tokens[caller] = value
        return cls(tokens)

    def authenticate(self, authorization: str | None) -> str | None:
        """Return the caller id for a ``Bearer <token>`` header, or ``None``."""
        if not authorization or not authorization.startswith("Bearer "):
            return None
        presented = authorization.removeprefix("Bearer ").encode()
        match: str | None = None
        for caller, token in self.tokens.items():  # check all: no early exit on match
            if hmac.compare_digest(presented, token.encode()):
                match = caller
        return match


def resolve_actor(caller: str, actor_header: str | None) -> str:
    """Audit ``actor``: the operator from the header if the orchestrator sent a valid one,
    otherwise the caller itself. The header from any other caller is ignored."""
    if caller == ORCHESTRATOR and actor_header and _ACTOR_RE.match(actor_header):
        return actor_header
    return caller
