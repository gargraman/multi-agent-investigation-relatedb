"""Scenario manifest catalog shared by specialist agents."""

from __future__ import annotations

import logging
from pathlib import Path

from nexus_contracts.scenario.loader import load_agent_manifest
from nexus_contracts.scenario.manifest import AgentManifest

log = logging.getLogger(__name__)


class ManifestCatalog:
    """Loads ``AGENT_MANIFESTS_DIR/<scenario_id>.json`` once per scenario (metadata only).

    These are the oracle-free projections generated by ``scripts/gen_scenario.py``; agents never
    mount the full ``data/scenarios`` manifests, so the oracle is not reachable from agent code.
    """

    def __init__(self, manifests_dir: Path) -> None:
        self.manifests_dir = manifests_dir
        self._cache: dict[str, AgentManifest] = {}

    def get(self, scenario_id: str) -> AgentManifest | None:
        if scenario_id in self._cache:
            return self._cache[scenario_id]
        path = self.manifests_dir / f"{scenario_id}.json"
        if not path.is_file():  # scenario_id is a ManifestId (no '/' or '..')
            return None
        try:
            manifest = load_agent_manifest(path)
        except Exception:
            log.exception("manifest failed to load", extra={"scenario_id": scenario_id})
            return None
        self._cache[scenario_id] = manifest
        return manifest

    def is_ready(self) -> bool:
        return self.manifests_dir.is_dir() and any(self.manifests_dir.glob("*.json"))
