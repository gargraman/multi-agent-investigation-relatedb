/**
 * gen-types: derive TypeScript types from the Pydantic-generated JSON Schemas.
 *
 * Usage:  npm run gen:types
 * Source: ../../contracts/schemas/<name>.schema.json (source of truth: contracts/src/nexus_contracts)
 * Output: src/api/generated/<name>.ts (committed; do not hand-edit, re-run this script instead)
 */
import { compileFromFile } from "json-schema-to-typescript";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../../contracts/schemas");
const outDir = resolve(here, "../src/api/generated");

const SCHEMAS = [
  "investigation",
  "investigation-create-request",
  "investigation-page",
  "timeline-event",
  "problem-details",
];

const banner =
  "/* eslint-disable */\n/**\n * GENERATED by scripts/gen-types.mjs from contracts/schemas. Do not edit by hand.\n */";

await mkdir(outDir, { recursive: true });
for (const name of SCHEMAS) {
  const ts = await compileFromFile(resolve(schemaDir, `${name}.schema.json`), {
    bannerComment: banner,
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    style: { singleQuote: false, semi: true },
  });
  await writeFile(resolve(outDir, `${name}.ts`), ts);
  console.log(`generated src/api/generated/${name}.ts`);
}

// Runtime enum constants (TS unions vanish at runtime; SSE needs the event-type list to subscribe).
const enums = new Map();
for (const name of SCHEMAS) {
  const schema = JSON.parse(await readFile(resolve(schemaDir, `${name}.schema.json`), "utf8"));
  for (const [defName, def] of Object.entries(schema.$defs ?? {})) {
    if (Array.isArray(def.enum)) enums.set(defName, def.enum);
  }
}
let out = `${banner}\n\n`;
for (const [defName, values] of [...enums.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  out += `export const ${defName}Values = ${JSON.stringify(values)} as const;\n`;
}
await writeFile(resolve(outDir, "enums.ts"), out);
console.log("generated src/api/generated/enums.ts");
